// ── Units ───────────────────────────────────────────────────────────────────

function unit(def: Partial<UnitDef> & Pick<UnitDef, "id" | "cls" | "side" | "cost" | "hp">): UnitDef {
  const infantry = def.cls === UnitClass.Infantry;
  return {
    buildTime: seconds(def.cost / 80),
    armor: infantry ? ArmorKind.None : ArmorKind.Light,
    speed: infantry ? 0.85 : 1.4,
    turnRate: infantry ? 0.6 : 0.12,
    turretTurnRate: 0.1,
    hasTurret: false,
    weapon: null,
    weapon2: null,
    sight: 5,
    radius: infantry ? 5 : 9,
    producedBy: null,
    requires: [],
    cargoCapacity: 0,
    crusher: false,
    selfHeal: 0,
    order: 0,
    ...def,
  };
}

