// ── Lookups ─────────────────────────────────────────────────────────────────

export function unitDef(id: UnitKindId): UnitDef {
  return UNITS[id];
}

export function structureDef(id: StructureKindId): StructureDef {
  return STRUCTURES[id];
}

export function weaponDef(id: string): WeaponDef {
  const w = WEAPONS[id];
  if (!w) throw new Error(`Unknown weapon: ${id}`);
  return w;
}

export function isUnitKind(id: string): id is UnitKindId {
  return Object.prototype.hasOwnProperty.call(UNITS, id);
}

export function isStructureKind(id: string): id is StructureKindId {
  return Object.prototype.hasOwnProperty.call(STRUCTURES, id);
}

/** Everything the given side can ever build, sorted for the sidebar. */
export function buildableStructures(side: "soviet" | "allied"): StructureDef[] {
  return Object.values(STRUCTURES)
    .filter((s) => (s.side === side || s.side === "both") && s.id !== "conyard" && s.id !== "conyard_a")
    .sort((a, b) => a.order - b.order);
}

export function buildableUnits(side: "soviet" | "allied"): UnitDef[] {
  return Object.values(UNITS)
    .filter((u) => u.side === side || u.side === "both")
    .sort((a, b) => a.order - b.order);
}

export function damageAgainst(w: WeaponDef, armor: ArmorKind): number {
  return w.damage * w.verses[armor];
}
