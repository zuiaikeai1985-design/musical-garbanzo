const tiles = (n: number): number => n * TILE;

/** Shorthand for a full verses row. */
function verses(
  none: number,
  wood: number,
  light: number,
  heavy: number,
  concrete: number,
): Record<ArmorKind, number> {
  return { none, wood, light, heavy, concrete };
}

